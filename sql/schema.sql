CREATE DATABASE IF NOT EXISTS cab_user_app CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE cab_user_app;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL DEFAULT '',
  mobile_number VARCHAR(20) NOT NULL UNIQUE,
  email VARCHAR(190) NULL UNIQUE,
  gender ENUM('Male','Female','Other') NULL,
  language VARCHAR(10) NOT NULL DEFAULT 'en',
  profile_photo_url TEXT NULL,
  phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
  profile_completed BOOLEAN NOT NULL DEFAULT FALSE,
  referral_code VARCHAR(32) NULL,
  referred_by VARCHAR(32) NULL,
  terms_accepted BOOLEAN NOT NULL DEFAULT FALSE,
  rating DECIMAL(3,2) NOT NULL DEFAULT 5.00,
  current_latitude DECIMAL(10,7) NULL,
  current_longitude DECIMAL(10,7) NULL,
  current_address VARCHAR(500) NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  deletion_status ENUM('NONE','SCHEDULED','COMPLETED') NOT NULL DEFAULT 'NONE',
  deletion_date DATE NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS otp_sessions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  session_id VARCHAR(80) NOT NULL UNIQUE,
  mobile_number VARCHAR(20) NOT NULL,
  purpose ENUM('LOGIN','REGISTER','CHANGE_PHONE','DELETE_ACCOUNT') NOT NULL,
  otp_hash VARCHAR(255) NOT NULL,
  verification_token_hash VARCHAR(255) NULL,
  verified BOOLEAN NOT NULL DEFAULT FALSE,
  attempts INT NOT NULL DEFAULT 0,
  expires_at DATETIME NOT NULL,
  resend_after DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_otp_mobile_purpose (mobile_number, purpose)
);

CREATE TABLE IF NOT EXISTS vehicle_types (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  vehicle_type_id VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(80) NOT NULL,
  icon_url TEXT NULL,
  capacity INT NOT NULL DEFAULT 4,
  base_fare DECIMAL(10,2) NOT NULL DEFAULT 50,
  per_km DECIMAL(10,2) NOT NULL DEFAULT 12,
  per_minute DECIMAL(10,2) NOT NULL DEFAULT 1,
  nearest_eta_minutes INT NULL,
  is_available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS cities (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  city_id VARCHAR(40) NOT NULL UNIQUE,
  city_name VARCHAR(100) NOT NULL,
  min_lat DECIMAL(10,7) NULL, max_lat DECIMAL(10,7) NULL,
  min_lng DECIMAL(10,7) NULL, max_lng DECIMAL(10,7) NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS banners (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  banner_id VARCHAR(40) NOT NULL UNIQUE,
  city_id VARCHAR(40) NULL,
  image_url TEXT NOT NULL,
  title VARCHAR(200) NULL,
  redirect_type ENUM('NONE','URL','PROMO','SCREEN') NOT NULL DEFAULT 'NONE',
  redirect_value VARCHAR(500) NULL,
  sort_order INT NOT NULL DEFAULT 0,
  start_date DATETIME NULL, end_date DATETIME NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS rides (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ride_id VARCHAR(40) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  vehicle_type_id VARCHAR(40) NOT NULL,
  estimate_id VARCHAR(60) NULL,
  status ENUM('SEARCHING','DRIVER_ASSIGNED','DRIVER_ARRIVED','TRIP_STARTED','COMPLETED','CANCELLED_BY_USER','CANCELLED_BY_DRIVER','NO_DRIVER_FOUND','SCHEDULED') NOT NULL DEFAULT 'SEARCHING',
  pickup_lat DECIMAL(10,7) NOT NULL, pickup_lng DECIMAL(10,7) NOT NULL,
  pickup_address VARCHAR(500) NOT NULL,
  drop_lat DECIMAL(10,7) NOT NULL, drop_lng DECIMAL(10,7) NOT NULL,
  drop_address VARCHAR(500) NOT NULL,
  payment_method ENUM('CASH','WALLET','UPI','CARD') NOT NULL DEFAULT 'CASH',
  payment_status ENUM('PENDING','PAID','FAILED','REFUNDED') NOT NULL DEFAULT 'PENDING',
  estimated_fare DECIMAL(10,2) NOT NULL DEFAULT 0,
  final_fare DECIMAL(10,2) NULL,
  discount DECIMAL(10,2) NOT NULL DEFAULT 0,
  promo_code VARCHAR(40) NULL,
  note_for_driver VARCHAR(500) NULL,
  driver_id VARCHAR(40) NULL,
  ride_otp VARCHAR(8) NULL,
  cancellation_fee DECIMAL(10,2) NOT NULL DEFAULT 0,
  completed_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_rides_user FOREIGN KEY (user_id) REFERENCES users(id),
  INDEX idx_rides_user_created (user_id, created_at),
  INDEX idx_rides_status (status)
);

CREATE TABLE IF NOT EXISTS ride_timeline (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ride_id VARCHAR(40) NOT NULL,
  status VARCHAR(40) NOT NULL,
  note VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_timeline_ride (ride_id)
);

CREATE TABLE IF NOT EXISTS drivers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  driver_id VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NULL, phone_masked VARCHAR(30) NULL,
  photo_url TEXT NULL, rating DECIMAL(3,2) NOT NULL DEFAULT 5,
  total_trips INT NOT NULL DEFAULT 0,
  latitude DECIMAL(10,7) NULL, longitude DECIMAL(10,7) NULL,
  heading DECIMAL(6,2) NULL,
  vehicle_type_id VARCHAR(40) NULL,
  vehicle_type VARCHAR(80) NULL, make_model VARCHAR(100) NULL,
  vehicle_color VARCHAR(60) NULL, registration_number VARCHAR(30) NULL,
  is_available BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ride_ratings (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ride_id VARCHAR(40) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  rating TINYINT NOT NULL,
  tags JSON NULL,
  comment TEXT NULL,
  tip_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS wallet_transactions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  txn_id VARCHAR(50) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  type ENUM('CREDIT','DEBIT') NOT NULL,
  amount DECIMAL(10,2) NOT NULL,
  description VARCHAR(255) NOT NULL,
  ride_id VARCHAR(40) NULL,
  balance_after DECIMAL(10,2) NOT NULL,
  gateway_order_id VARCHAR(100) NULL,
  gateway_payment_id VARCHAR(100) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id),
  INDEX idx_wallet_user_created (user_id, created_at)
);

CREATE TABLE IF NOT EXISTS payments (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  payment_ref VARCHAR(50) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  ride_id VARCHAR(40) NULL,
  purpose ENUM('RIDE','WALLET_TOPUP') NOT NULL,
  payment_method VARCHAR(20) NOT NULL,
  gateway_order_id VARCHAR(100) NULL,
  gateway_payment_id VARCHAR(100) NULL,
  amount DECIMAL(10,2) NOT NULL,
  status ENUM('CREATED','PAID','FAILED') NOT NULL DEFAULT 'CREATED',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id),
  INDEX idx_payment_order (gateway_order_id)
);

CREATE TABLE IF NOT EXISTS saved_addresses (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  address_id VARCHAR(40) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  label ENUM('HOME','WORK','OTHER') NOT NULL DEFAULT 'OTHER',
  name VARCHAR(100) NOT NULL,
  address VARCHAR(500) NOT NULL,
  latitude DECIMAL(10,7) NOT NULL,
  longitude DECIMAL(10,7) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS promos (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE,
  title VARCHAR(200) NOT NULL,
  description TEXT NULL,
  discount_type ENUM('FLAT','PERCENT') NOT NULL,
  discount_value DECIMAL(10,2) NOT NULL,
  max_discount DECIMAL(10,2) NULL,
  min_fare DECIMAL(10,2) NOT NULL DEFAULT 0,
  valid_till DATETIME NULL,
  terms TEXT NULL,
  usage_limit INT NULL,
  used_count INT NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS support_faqs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  faq_id VARCHAR(40) NOT NULL UNIQUE,
  question VARCHAR(500) NOT NULL,
  answer TEXT NOT NULL,
  category VARCHAR(80) NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS support_tickets (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ticket_id VARCHAR(40) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  category ENUM('RIDE','PAYMENT','DRIVER','APP','OTHER') NOT NULL,
  ride_id VARCHAR(40) NULL,
  subject VARCHAR(200) NOT NULL,
  message TEXT NOT NULL,
  status ENUM('OPEN','IN_PROGRESS','RESOLVED') NOT NULL DEFAULT 'OPEN',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS support_messages (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ticket_id VARCHAR(40) NOT NULL,
  sender_type ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER',
  message TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_support_messages_ticket (ticket_id)
);

CREATE TABLE IF NOT EXISTS emergency_contacts (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  contact_id VARCHAR(40) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  name VARCHAR(120) NOT NULL,
  mobile_number VARCHAR(20) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS sos_events (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  sos_id VARCHAR(40) NOT NULL UNIQUE,
  ride_id VARCHAR(40) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  latitude DECIMAL(10,7) NOT NULL,
  longitude DECIMAL(10,7) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS shared_trips (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  share_id VARCHAR(50) NOT NULL UNIQUE,
  ride_id VARCHAR(40) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  expires_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
